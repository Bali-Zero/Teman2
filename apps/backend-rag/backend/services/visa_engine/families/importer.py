"""Law importer: law/<F>/*.json cards + family_<f>.json -> visa_types rows and a deterministic SQL migration."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
PRICES_PATH = HERE.parent.parent.parent / "data" / "bali_zero_official_prices_2026.json"

LAW_COLUMNS = (
    "family",
    "official_name_id",
    "permit_class",
    "is_sold",
    "price_keys",
    "entry_type",
    "sponsor",
    "apply_channel",
    "initial_stay_days",
    "extendable",
    "max_total_days",
    "max_total_months",
    "itap",
    "law_card",
    "source_url",
    "page_sha256",
    "retrieved_at",
    "card_sha256",
    "verification_status",
    "valid_from",
    "valid_until",
    "superseded_by",
)
CASTS = {
    "stay_options": "jsonb",
    "price_keys": "jsonb",
    "itap": "jsonb",
    "law_card": "jsonb",
    "retrieved_at": "timestamptz",
    "valid_from": "date",
    "valid_until": "date",
}
JSON_COLUMNS = {"price_keys", "itap", "law_card", "stay_options"}

SHA_COLUMNS = ("page_sha256", "card_sha256")

HEADER = """-- GENERATED by backend/services/visa_engine/families/importer.py from law/{family} cards
-- and family_{lower}.json. DO NOT EDIT BY HAND: change the cards, then regenerate with
--   python -m backend.services.visa_engine.families.importer --family {family} --emit-sql > <this file>
-- Only the Law columns are written on conflict; legacy columns (name, category, description,
-- duration, cost_visa, requirements, metadata) are never overwritten.

SET lock_timeout = '5s';
SET statement_timeout = '60s';
"""


def load_prices() -> dict:
    return json.loads(PRICES_PATH.read_text())["services"]


def _check_price_keys(code: str, keys: list[dict], prices: dict) -> None:
    for pk in keys:
        cat, item = pk["category"], pk["item_key"]
        if cat not in prices or item not in prices[cat]:
            raise ValueError(f"{code}: price key {cat!r}/{item!r} not found in price list")


def build_rows(family: str) -> list[dict]:
    fam = family.upper()
    data = json.loads((HERE / f"family_{fam.lower()}.json").read_text())
    prices = load_prices()
    rows = []
    for code in sorted(data["visas"]):
        guide = data["visas"][code]
        path = HERE / "law" / fam / f"{code}.json"
        raw = path.read_bytes()
        card = json.loads(raw)
        price_keys = guide["price_keys"]
        _check_price_keys(code, price_keys, prices)
        rows.append(
            {
                "code": code,
                "category": data["category"],
                "family": fam,
                "official_name_id": card["official_name_id"],
                "permit_class": data["permit_class"],
                "is_sold": guide.get("is_sold", True),
                "price_keys": price_keys,
                "entry_type": guide.get("entry_type", data["entry_type"]),
                "sponsor": (
                    None
                    if guide["sponsor_required"] is None
                    else "REQUIRED"
                    if guide["sponsor_required"]
                    else "CONDITIONAL"
                ),
                "apply_channel": None,
                "initial_stay_days": guide.get("stay_days"),
                "extendable": guide["extendable"],
                "max_total_days": guide.get("max_total_days"),
                "max_total_months": guide.get("max_total_months"),
                "itap": None,
                "law_card": card,
                "source_url": card["source_url"],
                "page_sha256": card["page_sha256"],
                "retrieved_at": card["retrieved_at"],
                "card_sha256": hashlib.sha256(raw).hexdigest(),
                "verification_status": (
                    "VERIFIED" if card.get("status") == "VERIFIED_FROM_SOURCE" else "TO_VERIFY"
                ),
                "valid_from": None,
                "valid_until": None,
                "superseded_by": None,
            }
        )
        if "stay_options" in guide:
            rows[-1]["stay_options"] = guide["stay_options"]
    return rows


def _text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def literal(column: str, value: Any) -> str:
    if value is None:
        return "NULL"
    if column in JSON_COLUMNS:
        body = json.dumps(value, ensure_ascii=False, sort_keys=True)
        tag = "j"
        while f"${tag}$" in body:
            tag += "j"
        return f"${tag}${body}${tag}$::jsonb"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    text = _text(value)
    return f"{text}::{CASTS[column]}" if column in CASTS else text


def emit_sql(family: str) -> str:
    fam = family.upper()
    rows = build_rows(fam)
    law_columns = _law_columns(rows)
    parts = [HEADER.format(family=fam, lower=fam.lower())]
    parts.append(_case_guard_sql(rows))
    cols = ("code", "name", "category", *law_columns)
    updates = ",\n    ".join(f"{c} = EXCLUDED.{c}" for c in law_columns)
    for row in rows:
        vals = [_text(row["code"]), _text(row["official_name_id"]), _text(row["category"])]
        vals += [literal(c, row[c]) for c in law_columns]
        lines = []
        for col, val in zip(cols, vals, strict=True):
            sep = "," if col != cols[-1] else ""
            # sha256 hex digests are content hashes, not secrets.
            tag = "  -- pragma: allowlist secret" if col in SHA_COLUMNS else ""
            lines.append(f"{val}{sep}{tag}")
        parts.append(
            f"\nINSERT INTO visa_types ({', '.join(cols)})\nVALUES (\n    "
            + "\n    ".join(lines)
            + f"\n)\nON CONFLICT (code) DO UPDATE SET\n    {updates};\n"
        )
    parts.append(_rollback_sql(rows))
    return "".join(parts)


def _law_columns(rows: list[dict]) -> tuple[str, ...]:
    # C's applied migration remains byte-identical; stay options are opt-in per family.
    return (*LAW_COLUMNS, "stay_options") if any("stay_options" in r for r in rows) else LAW_COLUMNS


def _case_guard_sql(rows: list[dict]) -> str:
    codes = ", ".join(_text(r["code"]) for r in rows)
    return (
        "\n-- Guard: refuse to run if a row already holds one of these codes in another case\n"
        "-- (the UNIQUE on code is case-sensitive, so the upsert below would add a duplicate).\n"
        "DO $guard$\nBEGIN\n"
        f"    IF EXISTS (SELECT 1 FROM visa_types WHERE code <> upper(code) AND upper(code) IN ({codes})) THEN\n"
        "        RAISE EXCEPTION 'visa_types holds a non-uppercase duplicate of a family code; fix the case first';\n"
        "    END IF;\n"
        "END\n$guard$;\n"
    )


def _rollback_sql(rows: list[dict]) -> str:
    resets = []
    for c in _law_columns(rows):
        if c == "price_keys":
            resets.append("price_keys = '[]'::jsonb")
        elif c == "verification_status":
            resets.append("verification_status = 'TO_VERIFY'")
        else:
            resets.append(f"{c} = NULL")
    codes = ", ".join(_text(r["code"]) for r in rows)
    return (
        "\n-- === ROLLBACK ===\n\n"
        "-- Clears only the Law columns of these codes; rows and legacy columns stay.\n"
        "UPDATE visa_types SET\n    " + ",\n    ".join(resets) + f"\nWHERE code IN ({codes});\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--family", required=True)
    ap.add_argument("--emit-sql", action="store_true")
    ap.add_argument("--check", metavar="FILE")
    args = ap.parse_args(argv)
    sql = emit_sql(args.family)
    if args.check:
        if Path(args.check).read_text() != sql:
            sys.stderr.write(f"DRIFT: {args.check} differs from importer output\n")
            return 1
        return 0
    if args.emit_sql:
        sys.stdout.write(sql)
        return 0
    ap.error("one of --emit-sql / --check is required")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
