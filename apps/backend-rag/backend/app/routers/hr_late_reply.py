"""
HR Late Reply Router — public reply form for late-arrival incidents.

Auth model: the unguessable ``reply_token`` (32 bytes URL-safe, generated by
``AttendanceMonitor._send_incident_opened_notification``) IS the auth. Anyone
who can read the email can submit a reply for that one incident, and only
that one. The token is invalidated by ``reply_received_at`` becoming non-null.

Endpoints:
    GET  /api/hr/late-reply/{incident_id}?token=<token>
        → returns a minimal HTML form with a textarea, or an error page if the
          token is wrong / the reply has already been submitted.
    POST /api/hr/late-reply/{incident_id}
        → form-urlencoded body with ``token`` + ``reason``; updates the row and
          returns a confirmation page.

The router has no FastAPI dependencies (no auth, no rate-limiter wrapper) on
purpose: it must work for unauthenticated team members opening the link from
their phone email client. The token check is done inline.
"""

from __future__ import annotations

import logging
import secrets
from uuid import UUID

import asyncpg
from fastapi import APIRouter, Depends, Form, HTTPException, Query
from fastapi.responses import HTMLResponse

from backend.app.dependencies import get_database_pool
from backend.services.analytics.attendance_monitor import (
    STATE_AWAITING_REPLY,
    STATE_REMINDER_SENT,
    STATE_RESOLVED,
    STATE_RESOLVED_LATE,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/hr", tags=["hr-late-reply"])


