@router.get(
    "/late-reply/{incident_id}",
    response_class=HTMLResponse,
    include_in_schema=False,
)
async def get_late_reply_form(
    incident_id: UUID,
    token: str = Query(..., min_length=10, max_length=128),
    db_pool: asyncpg.Pool = Depends(get_database_pool),
) -> HTMLResponse:
    """Serve the reply form. Returns the form HTML or an error page."""
    async with db_pool.acquire() as conn:
        row = await conn.fetchrow(
            """
            SELECT id, reply_token, reply_received_at, late_date, state
              FROM attendance_late_incidents
             WHERE id = $1
            """,
            incident_id,
        )

    if row is None or not secrets.compare_digest(row["reply_token"], token):
        logger.warning(
            "get_late_reply_form: invalid token for incident_id=%s", incident_id,
        )
        return HTMLResponse(_render_invalid(), status_code=404)

    if row["reply_received_at"] is not None:
        return HTMLResponse(_render_already_replied(), status_code=200)

    return HTMLResponse(
        _render_form(
            incident_id=incident_id,
            token=token,
            late_date=row["late_date"].strftime("%d/%m/%Y"),
        ),
    )


@router.post(
    "/late-reply/{incident_id}",
    response_class=HTMLResponse,
    include_in_schema=False,
)
async def post_late_reply(
    incident_id: UUID,
    token: str = Form(..., min_length=10, max_length=128),
    reason: str = Form(..., min_length=1, max_length=2000),
    db_pool: asyncpg.Pool = Depends(get_database_pool),
) -> HTMLResponse:
    """
    Persist the reply. Updates ``reply_received_at`` + ``reply_content`` only
    if the token matches and a reply has not yet been recorded.

    State transition (mirrors the cron logic so the dashboard is correct
    immediately, even before the next scan runs):
        AWAITING_REPLY -> RESOLVED
        REMINDER_SENT  -> RESOLVED_LATE
        ESCALATED      -> stays ESCALATED (history preserved)
    """
    async with db_pool.acquire() as conn:
        row = await conn.fetchrow(
            """
            SELECT reply_token, reply_received_at, state
              FROM attendance_late_incidents
             WHERE id = $1
            """,
            incident_id,
        )

        if row is None or not secrets.compare_digest(row["reply_token"], token):
            logger.warning(
                "post_late_reply: invalid token for incident_id=%s", incident_id,
            )
            raise HTTPException(status_code=404, detail="invalid token")

        if row["reply_received_at"] is not None:
            return HTMLResponse(_render_already_replied(), status_code=200)

        next_state = {
            STATE_AWAITING_REPLY: STATE_RESOLVED,
            STATE_REMINDER_SENT: STATE_RESOLVED_LATE,
        }.get(row["state"], row["state"])  # ESCALATED stays ESCALATED

        await conn.execute(
            """
            UPDATE attendance_late_incidents
               SET reply_received_at = NOW(),
                   reply_content     = $1,
                   state             = $2
             WHERE id = $3
            """,
            reason.strip(),
            next_state,
            incident_id,
        )

    logger.info(
        "post_late_reply: incident %s resolved (state=%s, %d chars)",
        incident_id,
        next_state,
        len(reason),
    )
    return HTMLResponse(_render_success(), status_code=200)
