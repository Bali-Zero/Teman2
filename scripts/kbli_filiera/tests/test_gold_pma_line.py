"""Guilt, innocence and a shrink-only ledger for gold's `**PMA:**` sentence.

The defect this pins: `apps/mouth/data/kbli-gold-all.json` OVERRIDES canonical
on every rendered page, and its `whatYouNeed` restates the foreign-ownership
cap — a fact it does not own. On 2026-08-07 that restatement disagreed with the
canonical record on 20 comparable codes, sixteen of them promising MORE foreign
ownership than the law allows, live, including scheduled airlines (`51101`,
cap 49) and Umrah/Hajj travel (`79122`, cap 0).

Why a test and not just a cure: the sentence is machine-generated by three
different enrichment scripts, so the next regeneration re-creates it. A cure
without a guard is a cure with a countdown.

The exception list is NAMED and may only SHRINK. Each entry says why a compiler
must not touch it — "needs adjudication" is a state, not a licence, and the
count in `test_exception_list_only_shrinks` is the ratchet.
"""

