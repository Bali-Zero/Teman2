# ── guilt ───────────────────────────────────────────────────────────────────


def test_guilt_a_pma_marker_with_the_colon_inside_the_bold_is_seen():
    """`41020` wrote `**PMA: TERBUKA 100% — …**`. The first version of the
    sentence pattern was written from the `**PMA:**` shape already in hand and
    was blind to this one, on a cap-0 code."""
    canon, gold = _mini(0, "**PMA: TERBUKA 100% — fully open to foreign ownership.**")
    f = C.scan(gold, canon)
    assert "90001" in f and f["90001"]["stated"] == 100 and f["90001"]["more_open"]


def _mini(cap, sentence, status="TERBATAS"):
    canon = {"90001": {"kode_kbli_2025": "90001", "pma_max_asing": cap,
                       "pma_status": status, "judul": "Test"}}
    gold = {"90001": {"whatYouNeed": f"1. **NIB via OSS**\n\n{sentence}\n\nmore text"}}
    return canon, gold


def test_guilt_a_more_open_figure_is_caught():
    canon, gold = _mini(49, "**PMA:** Fully open — 100% foreign ownership allowed.")
    f = C.scan(gold, canon)
    assert "90001" in f and f["90001"]["more_open"] is True
    assert f["90001"]["is_default"] is True


def test_guilt_a_more_restrictive_figure_is_caught_but_refused():
    canon, gold = _mini(100, "**PMA:** Restricted — max 49% foreign ownership.", "TERBUKA")
    f = C.scan(gold, canon)
    assert "90001" in f and f["90001"]["more_open"] is False
    patch, refused = C.plan(f, gold)
    assert patch == {} and "90001" in refused


def test_guilt_closed_wording_counts_as_zero_not_as_no_figure():
    """`Closed to foreign investment` states 0% without writing a digit — a
    reader of the sentence knows that, and so must the scan."""
    canon, gold = _mini(100, "**PMA:** Closed to foreign investment — domestic entities only.", "TERBUKA")
    assert C.scan(gold, canon)["90001"]["stated"] == 0


def test_guilt_a_hand_authored_sentence_is_refused_not_rewritten():
    canon, gold = _mini(
        0, "**PMA:** Fully open — 100% foreign ownership, WITH mandatory Kemenkes authorization."
    )
    f = C.scan(gold, canon)
    assert f["90001"]["is_default"] is False
    patch, refused = C.plan(f, gold)
    assert patch == {} and "90001" in refused


# ── innocence ───────────────────────────────────────────────────────────────


def test_innocence_an_agreeing_sentence_is_not_a_finding():
    canon, gold = _mini(49, "**PMA:** Restricted — max 49% foreign ownership.")
    assert C.scan(gold, canon) == {}


def test_innocence_a_percentage_elsewhere_in_the_field_is_not_the_pma_figure():
    """The field is full of numbers — capital, timelines, other percentages.
    Only the PMA sentence's own figure may convict it."""
    canon = {"90001": {"kode_kbli_2025": "90001", "pma_max_asing": 100,
                       "pma_status": "TERBUKA", "judul": "Test"}}
    gold = {"90001": {"whatYouNeed":
        "Foreign staff may not exceed 30% of headcount.\n"
        "**PMA:** Fully open — 100% foreign ownership allowed.\n"
        "Local content target: 40%."}}
    assert C.scan(gold, canon) == {}


def test_innocence_a_code_with_no_pma_sentence_is_not_a_finding():
    canon = {"90001": {"kode_kbli_2025": "90001", "pma_max_asing": 49,
                       "pma_status": "TERBATAS", "judul": "Test"}}
    gold = {"90001": {"whatYouNeed": "1. **NIB via OSS** — auto-issued."}}
    assert C.scan(gold, canon) == {}


def test_innocence_replacement_never_touches_the_rest_of_the_field():
    canon, gold = _mini(49, "**PMA:** Fully open — 100% foreign ownership allowed.")
    patch, _ = C.plan(C.scan(gold, canon), gold)
    new = patch["90001"]["new"]
    assert new.startswith("1. **NIB via OSS**") and new.endswith("more text")
    assert "Fully open" not in new


