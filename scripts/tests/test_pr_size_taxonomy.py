    fpath = tmp_path / "fixture.json"
    fpath.write_text(json.dumps(fixture))
    out = _run_cli("--fixture", str(fpath))
    assert "#100" in out and "split-required" in out
    assert "#101" in out and "exempt(evidence)" in out


