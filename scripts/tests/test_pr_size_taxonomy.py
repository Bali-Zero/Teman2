import pr_size_taxonomy as pst  # noqa: E402


def _pr(n: int, files: list[tuple[str, int, int]], title: str = "synthetic", merge_sha=None) -> dict:
    return {"n": n, "t": title, "mergeSha": merge_sha,
            "files": [{"p": p, "a": a, "d": d} for p, a, d in files]}


