#!/usr/bin/env python3
"""
excel_to_masterpiece.py - The "Vision Factory" Parser
-----------------------------------------------------
Parses Excel files generated by Adobe Acrobat into the Masterpiece JSON format.
Handles merged cells, headers, and cleaning of OCR artifacts.

Usage:
    python3 scripts/vision_factory/excel_to_masterpiece.py [input_xlsx] [output_json]
"""

import sys
import json
import re
import pandas as pd
import numpy as np
from pathlib import Path

def clean_text(text):
    if not isinstance(text, str):
        return ""
    # Remove OCR noise like "r.c.", "t.c." which often appear
    text = re.sub(r'\b[rt]\.?c\.?\b', '', text, flags=re.IGNORECASE)
    # Fix spacing
    text = re.sub(r'\s+', ' ', text).strip()
    return text

def parse_excel(xlsx_path):
    """
    Reads Excel and attempts to map columns to Masterpiece schema.
    Adobe export often creates many unnamed columns.
    We need heuristic mapping.
    """
    try:
        # Read without header first to find the real header row
        df_raw = pd.read_excel(xlsx_path, header=None) 
    except Exception as e:
        print(f"Error reading {xlsx_path}: {e}")
        return []

    # Simple heuristic: Identify header row by looking for keywords
    header_idx = None
    for idx, row in df_raw.iterrows():
        row_str = " ".join([str(x) for x in row.values]).lower()
        if "kode" in row_str and "judul" in row_str:
            header_idx = idx
            break
            
    if header_idx is None:
        print(f"Could not find header row in {xlsx_path}. Assuming raw structure.")
        return []

    # Reload with header
    df = pd.read_excel(xlsx_path, header=header_idx)
    
    # PRE-CLEANING: Adobe often puts "-" or specific placeholders in empty cells
    # We must treat them as NaN for ffill to work
    df.replace([r'^\s*-\s*$', r'^\s*$'], np.nan, regex=True, inplace=True)
    
    # Forward fill merged cells (crucial for KBLIs spanning pages/rows)
    df = df.ffill()
    
    records = []
    
    # Identify key columns by flexible matching
    col_map = {}
    for col in df.columns:
        c_lower = str(col).lower()
        if "kode" in c_lower: col_map["kode"] = col
        elif "judul" in c_lower: col_map["judul"] = col
        elif "ruang" in c_lower or "lingkup" in c_lower: col_map["ruang"] = col
        elif "skala" in c_lower: col_map["skala"] = col
        elif "risiko" in c_lower: col_map["risiko"] = col
        elif "perizinan" in c_lower: col_map["perizinan"] = col
        elif "persyaratan" in c_lower: col_map["persyaratan"] = col
        elif "kewajiban" in c_lower: col_map["kewajiban"] = col
        elif "waktu" in c_lower or "sla" in c_lower: col_map["timeline"] = col
        elif "kewenangan" in c_lower or "authority" in c_lower: col_map["authority"] = col
        elif "parameter" in c_lower: col_map["parameter"] = col

    # Iterate rows
    for idx, row in df.iterrows():
        # Build record object
        rec = {}
        
        # Safely get values
        code = str(row.get(col_map.get("kode"), "")).strip()
        
        # Skip garbage rows (e.g. repeated headers) or invalid codes
        if not code or code.lower() == "kode" or code.lower() == "nan":
            continue
            
        rec["kode"] = code
        rec["judul"] = clean_text(row.get(col_map.get("judul")))
        rec["ruang"] = clean_text(row.get(col_map.get("ruang")))
        rec["skala"] = clean_text(row.get(col_map.get("skala")))
        rec["risiko"] = clean_text(row.get(col_map.get("risiko")))
        
        # New robust mapping
        rec["perizinan"] = clean_text(row.get(col_map.get("perizinan")))
        rec["persyaratan"] = clean_text(row.get(col_map.get("persyaratan")))
        rec["kewajiban"] = clean_text(row.get(col_map.get("kewajiban")))
        rec["timeline"] = clean_text(row.get(col_map.get("timeline")))
        rec["authority"] = clean_text(row.get(col_map.get("authority")))
        # If parameter exists, map it
        if "parameter" in col_map:
            rec["parameter"] = clean_text(row.get(col_map.get("parameter")))
        
        rec["checklists_umku"] = []
        rec["intelligence_tags"] = []
        
        records.append(rec)
        
    return records

def main():
    if len(sys.argv) < 3:
        print("Usage: python3 excel_to_masterpiece.py <input_xlsx> <output_json>")
        return 
        
    input_xlsx = Path(sys.argv[1])
    output_json = Path(sys.argv[2])
    
    records = parse_excel(input_xlsx)
    
    # Wrap in Masterpiece Envelope
    masterpiece = {
        "lampiran": input_xlsx.stem, # Approximation
        "total_records": len(records),
        "intelligence_level": "Vision Factory V1",
        "data": records
    }
    
    with open(output_json, 'w') as f:
        json.dump(masterpiece, f, indent=2, ensure_ascii=False)
        
    print(f"Extracted {len(records)} records to {output_json}")

if __name__ == "__main__":
    main()
